# ---------------------------------------------------------------- symbols
@dataclass
class Sym:
    name: str                 # $NAME_SYM
    pins: dict                # terminal name -> (x, y); the members of a bus pin share one point
    text: str                 # RNL DEFINE-SYMBOL statement
    buses: dict = field(default_factory=dict)   # bus label (UP<12:0>) -> terminal names, MSB first
    dirs: dict = field(default_factory=dict)    # terminal name -> direction a wire leaves its pin at R0


def _sym(b: SymBuilder, comment: str | None = None) -> Sym:
    return Sym(b.name, dict(b.pins), b.define(comment), dict(b.buses), dict(b.dirs))


def box_symbol(sym: str, title: str, ports: list[tuple], min_w: int = 8) -> Sym:
    """Generic rectangle with pins on its sides. ports: [(terminal name, side)] or
    [(terminal name, side, bus)] in terminal order; consecutive members of one bus make a bus pin."""
    full = [(p[0], p[1], p[2] if len(p) > 2 else None) for p in ports]
    return _sym(symbols.box(sym, title, full, min_w=min_w))


def cdac_sw_symbol() -> tuple[Sym, list[str]]:
    """Switch matrix of the behavioral CDAC: 26 bottom-plate pins on top at pitch 3
    (aligned with the capacitors), the 26 controls below them. Returns (symbol, terminal order)."""
    a = Arch.load()
    js = list(range(len(a.w) - 1, -1, -1))
    halves = [f"B{t}{j}" for j in js for t in "HL"]
    ctrls = [f"{t}{j}" for j in js for t in ("DH", "RL")]
    left = ["VIN", "VG", "VREFP", "VREFN", "CONV"]
    order = left + [f"DH{j}" for j in js] + [f"RL{j}" for j in js] + halves + ["VSS"]
    b = symbols.cdac_sw("$ADC_CDAC_SW_VA_SYM", order, halves, ctrls)
    return _sym(b, "adc_cdac_sw_va: the switch matrix of the behavioral CDAC, aligned with its 26 halves"), order


@lru_cache
def block_symbols() -> dict[str, Sym]:
    out = {}
    for b in blocks().values():
        sym = f"${b.name.upper()}_SYM"
        draw = symbols.BLOCKS.get(b.name)
        if draw is None:
            out[b.name] = box_symbol(sym, b.name, [(p.name, p.side, p.bus) for p in b.ports])
        else:
            out[b.name] = _sym(draw(sym, b.port_names), f"{b.name}: {b.raw.get('title', '')}".rstrip(": "))
    return out


def _va_cfg() -> dict:
    with open(REPO_ROOT / "specs" / "va_modules.yaml", encoding="utf-8") as f:
        return yaml.safe_load(f)["modules"]


def va_port_list(mod: str) -> list[tuple[str, str, str | None]]:
    """[(terminal, side, bus)] in terminal order; vector ports expand MSB first."""
    cfg = _va_cfg()[mod]
    if "symbol_of" in cfg:
        return [(p.name, p.side, p.bus) for p in blocks()[cfg["symbol_of"]].ports]
    out = []
    for p in cfg["ports"]:
        if "bus" in p:
            step = -1 if p["msb"] >= p["lsb"] else 1
            out += [(f"{p['bus']}{i}", p["side"], p["bus"]) for i in range(p["msb"], p["lsb"] + step, step)]
        else:
            out.append((p["name"], p["side"], None))
    return out


def va_ports(mod: str) -> list[tuple[str, str]]:
    return [(p, side) for p, side, _ in va_port_list(mod)]


@lru_cache
def va_symbols() -> dict[str, Sym]:
    out = {}
    for mod, cfg in _va_cfg().items():
        if cfg.get("symbol") == "generated":
            continue
        if "symbol_of" in cfg:
            out[mod] = block_symbols()[cfg["symbol_of"]]
            continue
        sym = f"${mod.upper()}_SYM"
        draw = symbols.VA.get(mod)
        if draw is None:
            out[mod] = box_symbol(sym, cfg.get("title", mod), va_port_list(mod))
        else:
            out[mod] = _sym(draw(sym, [p for p, _ in va_ports(mod)]), f"{mod}: {cfg.get('title', '')}")
    return out


def _device(model: str, terms: list[str]) -> str:
    return f'  @DEVICE(name="*", model="{model}", terminals=[{", ".join(chr(34) + t + chr(34) for t in terms)}])'


def gen_rnl_blocks() -> str:
    bl = blocks()
    syms = block_symbols()
    out = [f"/* adc28-blocks 0.1: {GEN_HEADER}.",
           "   One DEVICE declaration (terminal order = subckt port order) and one block",
           "   symbol per block of specs/blocks/*.yaml, drawn in tools/adcflow/symbols.py.",
           "   Pins bind by terminal number; a bus (UP12 .. UP0) is one bus pin, drawn bold",
           "   with its width. */",
           '@RNL(type="header") {',
           '  @VERSION("0.3");',
           '  @PACKAGE(name="adc28-blocks", version="0.1");',
           ";\n".join(_device(b.name, b.port_names) for b in bl.values()),
           "}", "", "@RNL {",
           ";\n\n".join(syms[b].text for b in bl) + ";", ""]
    out.append(";\n".join(f'  # @SELECT-INSTANCE(model="{b}") => @SET-SYMBOL {syms[b].name}' for b in bl))
    out.append("}")
    return "\n".join(out) + "\n"


def gen_rnl_va() -> str:
    cfg = {m: c for m, c in _va_cfg().items() if c.get("symbol") != "generated"}
    syms = va_symbols()
    sw, sw_order = cdac_sw_symbol()
    devs = [_device(m, [p for p, _ in va_ports(m)]) for m in cfg]
    devs.append(_device("adc_cdac_sw_va", sw_order))
    own = [syms[m].text for m in cfg if "symbol_of" not in cfg[m]] + [sw.text]
    rules = [f'  # @SELECT-INSTANCE(model="{m}") => @SET-SYMBOL {syms[m].name}' for m in cfg]
    rules.append('  # @SELECT-INSTANCE(model="adc_cdac_sw_va") => @SET-SYMBOL $ADC_CDAC_SW_VA_SYM')
    out = [f"/* adc28-va 0.1: {GEN_HEADER}.",
           "   DEVICE declarations and symbols of the Verilog-A modules of the behavioral",
           "   views and testbenches (specs/va_modules.yaml), drawn in tools/adcflow/symbols.py.",
           "   Modules with the ports of a block reuse that block's symbol. */",
           '@RNL(type="header") {',
           '  @VERSION("0.3");',
           '  @PACKAGE(name="adc28-va", version="0.1");',
           '  @USE-PACKAGE(name="adc28-blocks", version="0.1", path="adc28_blocks.rnl");',
           ";\n".join(devs), "}", "", "@RNL {",
           ";\n\n".join(own) + ";", "", ";\n".join(rules), "}"]
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- VA constants
def gen_va_params() -> str:
    a = Arch.load()
    w = [int(x) for x in a.w]
    s = [int(x) for x in a.sampled]
    lines = [f"// {GEN_HEADER}",
             "`ifndef ADC_ARCH_VAMS",
             "`define ADC_ARCH_VAMS",
             f"`define ADC_NCAP {len(w)}",
             f"`define ADC_NDEC {a.n_dec}",
             f"`define ADC_VREF {a.vref}",
             f"`define ADC_CU {a.cu:.6e}",
             f"`define ADC_CS {a.c_s:.6e}",
             f"`define ADC_LSB {a.lsb:.6e}",
             "// cap weights, index j = 12 .. 0 (decision order)"]
    for i, (wj, sj) in enumerate(zip(w, s)):
        j = len(w) - 1 - i
        lines.append(f"`define ADC_W{j} {wj}")
        lines.append(f"`define ADC_S{j} {sj}")
    lines.append("`endif")
    return "\n".join(lines) + "\n"


def gen_va_funcs() -> str:
    """Analog functions to `include inside a module: capw(j), caps(j), outw(i)."""
    a = Arch.load()
    n = len(a.w)
    L = [f"// {GEN_HEADER}",
         "// `include inside a module body (after `include \"adc_arch.vams\").",
         "analog function real capw;   // weight of cap j (LSB)",
         "  input j; integer j;",
         "  begin",
         "    case (j)"]
    L += [f"      {j}: capw = `ADC_W{j};" for j in range(n - 1, -1, -1)]
    L += ["      default: capw = 0;", "    endcase", "  end", "endfunction", "",
          "analog function integer caps;  // 1 = cap j samples the input",
          "  input j; integer j;",
          "  begin",
          "    case (j)"]
    L += [f"      {j}: caps = `ADC_S{j};" for j in range(n - 1, -1, -1)]
    L += ["      default: caps = 0;", "    endcase", "  end", "endfunction", "",
          "analog function real outw;   // output weight of D<i>",
          "  input i; integer i;",
          "  begin",
          "    case (i)"]
    for i, wv in enumerate(a.out_weights):
        L.append(f"      {a.n_dec - 1 - i}: outw = {int(wv)};")
    L += ["      default: outw = 0;", "    endcase", "  end", "endfunction"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- behavioral CDAC
def gen_behav_cdac() -> str:
    """Behavioral CDAC: the 26 real half capacitors + one Verilog-A switch matrix.

    The capacitors are the actual array (w * cu / 2 per half); input switches and
    drivers are adc_cdac_sw_va; the top-plate switch is a relay; adc_ktc_va adds
    the sampled kT/C noise of the top node (enabled by the global noise_en).
    """
    a = Arch.load()
    n = len(a.w)
    js = list(range(n - 1, -1, -1))
    sw, sw_order = cdac_sw_symbol()
    ports = blocks()["adc_cdac"].port_names
    halves = [(f"B{t}{j}", f"C{t}{j}", j, t) for j in js for t in "HL"]
    wsum = int(a.w.sum())
    L = ["// adc_cdac, behavioral view: one side of the split-capacitor redundant CDAC",
         "// @RNL(type=\"header\") {",
         "//   @VERSION(\"0.3\");",
         "//   @USE-PACKAGE(name=\"adc28\", version=\"0.1\", path=\"../rnl/adc28.rnl\")",
         "// }",
         f"// {GEN_HEADER} (specs/arch.yaml, cdac section)",
         "// Uses the deck globals noise_en and tempc.",
         "simulator lang=spectre",
         ""]
    pl = " ".join(ports)
    L += [f"subckt adc_cdac ({pl[:pl.index(' DH12')]} \\",
          f"        {pl[pl.index('DH12'):pl.index(' RL12')]} \\",
          f"        {pl[pl.index('RL12'):]})",
          f"parameters cu={a.cu:g} cp_ratio={a.raw['cdac']['cp_top_ratio']} ron_in=25 tau_drv=12p ron_top=20",
          "// input switches (gate VG), tri-state VREFP/VREFN drivers, neutral states",
          f"ISW ({' '.join(sw_order[:5])} \\",
          f"        {' '.join(sw_order[5:18])} \\",
          f"        {' '.join(sw_order[18:31])} \\",
          f"        {' '.join(sw_order[31:44])} \\",
          f"        {' '.join(sw_order[44:])}) adc_cdac_sw_va cu=cu ron_in=ron_in tau_drv=tau_drv",
          "// capacitor array: weight w = two halves of w*cu/2 (H: neutral VREFP, L: neutral VREFN)"]
    for net, inst, j, t in halves:
        L.append(f"{inst} ({net} TOP) capacitor c={a.w[n - 1 - j] / 2:g}*cu")
    L += ["// top-plate parasitic: routing, switch junctions, comparator input",
          f"CP (TOP VSS) capacitor c=cp_ratio*{wsum}*cu",
          "// top-plate reset switch (PHI_S high = track) in series with the sampled kT/C source",
          "STOP (TOP NK PHI_S VSS) relay vt1=0.35 vt2=0.55 ropen=1e12 rclosed=ron_top",
          f"IKTC (NK VCM PHI_S VSS) adc_ktc_va ctot=(1+cp_ratio)*{wsum}*cu tempc=tempc en=noise_en"]

    s = Sheet()
    s.emit("/* --- semantics --- */")
    s.emit("&VSS @ADD-TO $GROUND_NET_SET;")
    s.emit("/* one array: every half is a matched multiple of the unit cu; each weight is an H/L pair */")
    s.emit("{" + " ".join(f"#{i}" for _, i, _, _ in halves) + "} @AS $MATCHED;")
    for j in js:
        s.emit(f"{{#CH{j} #CL{j}}} @AS $MATCHED;")
        s.emit(f"{{#CH{j} #CL{j}}} @GROUP;")
    s.emit("/* the top plate: the array, its parasitic, the reset switch and the sampled kT/C noise */")
    s.emit('{#CP #STOP #IKTC} @AS(direction="left-to-right") $FLOW;')
    s.emit("/* --- placement: switch matrix at the bottom, each half above its bottom-plate pin --- */")
    isw = s.place("ISW", sw.pins, 0, 0)
    top_y = isw.pin(halves[0][0])[1] + 8                     # the top-plate line
    caps = {}
    for net, inst, j, t in halves:
        x, y = isw.pin(net)
        caps[inst] = s.place(inst, {"p": (0, 2), "n": (0, -2)}, x, y + 4, "MX")
    x_cp = isw.pin("VSS")[0] + 5                              # parasitic cap right of the array
    cp = s.place("CP", {"p": (0, 2), "n": (0, -2)}, x_cp, top_y - 4)
    stop = s.place("STOP", dict(zip(("TOP", "NK", "PHI_S", "VSS"),
                                    STD_PINS["$VOLTAGE_CONTROLLED_SWITCH"].values())), x_cp + 10, top_y)
    ktc_pins = va_symbols()["adc_ktc_va"].pins
    ktc = s.place("IKTC", ktc_pins, x_cp + 20, top_y - 8)
    s.emit("/* --- bottom plates --- */")
    for net, inst, j, t in halves:
        s.wire(net, f"#ISW:{net}", f"#{inst}:1")
    s.emit("/* --- top plate: one line across the array to the reset switch --- */")
    pts = []
    for k, (net, inst, j, t) in enumerate(halves):
        x, _ = caps[inst].pin("n")
        pts.append(s.point(f"t{k}", x, top_y, junction=k > 0))
        s.wire("TOP", pts[-1], f"#{inst}:2")
    pcp = s.point("tcp", x_cp, top_y, junction=True)
    ptop = s.point("ttop", x_cp + 4, top_y, junction=True)
    s.wire("TOP", *pts, pcp, ptop, "#STOP:1")
    s.wire("TOP", pcp, "#CP:1")
    s.port("TOP", x_cp + 4, top_y + 4, facing="down")
    s.wire("TOP", "%p_top:p", ptop)
    kx, ky = ktc.pin("P")
    s.wire("NK", "#STOP:2", (kx, top_y), "#IKTC:1")
    s.emit("/* --- sampling phase and VCM --- */")
    px, py = stop.pin("PHI_S")
    qx, qy = ktc.pin("PHI")
    phs = s.point("phs", px - 2, qy, junction=True)
    s.port("PHI_S", px - 2, qy - 5, facing="up")
    s.wire("PHI_S", "%p_phi_s:p", phs, (px - 2, py), "#STOP:3")
    s.wire("PHI_S", phs, "#IKTC:3")
    nx, ny = ktc.pin("N")
    s.port("VCM", nx, ny - 4, facing="up")
    s.wire("VCM", "%p_vcm:p", "#IKTC:2")
    s.emit("/* --- grounds --- */")
    x, y = cp.pin("n")
    s.wire("VSS", "#CP:2", s.ground("VSS", x, y - 2, "g_cp"))
    x, y = isw.pin("VSS")
    s.wire("VSS", "#ISW:VSS", s.ground("VSS", x + 2, y, "g_sw"))
    x, y = stop.pin("VSS")
    s.wire("VSS", "#STOP:4", s.ground("VSS", x + 2, y, "g_st"))
    x, y = ktc.pin("VSS")
    s.wire("VSS", "#IKTC:4", s.ground("VSS", x + 2, y, "g_ktc"))
    s.emit("/* --- inputs and references on the left --- */")
    for p in ("VREFP", "VIN", "VREFN", "VG", "CONV"):
        x, y = isw.pin(p)
        s.port(p, x - 4, y)
        s.wire(p, f"%p_{p.lower()}:p", f"#ISW:{p}")
    s.emit("/* PHI_SB and DVDD are not used by the behavioral view */")
    s.port("PHI_SB", isw.pin("VIN")[0] - 4, top_y - 2)
    s.port("DVDD", isw.pin("VIN")[0] - 4, top_y)
    s.emit("/* --- control buses: each control pin taps the DH or the RL bus below the matrix --- */")
    for c, dy in (("DH", 3), ("RL", 5)):
        names = [f"{c}{j}" for j in js]
        taps = []
        for name in names:
            x, y = isw.pin(name)
            taps.append(s.point(f"{c.lower()}{name[2:]}", x, y - dy, junction=name != names[-1]))
            s.wire(name, f"#ISW:{name}", taps[-1])
        rail_y = isw.pin(names[0])[1] - dy
        s.bus_wire(f"bus_{c.lower()}", names, s.bus_port(f"p_{c.lower()}", names, isw.pin("CONV")[0] - 4, rail_y),
                   *taps)
    s.emit("/* --- annotations: half names beside each capacitor, the weight above each pair --- */")
    for net, inst, j, t in halves:
        x, y = caps[inst].pin("p")
        s.emit(f'#{inst} @TEXT("", key="value");')
        s.emit(f'#{inst} @TEXT("${{name}}", key="name", size=0.5, rotate=90, halign="middle") '
               f"=> @PLACE({x + 1.3:g}, {y + 2:g});")
    for j in js:
        x = caps[f"CH{j}"].pin("p")[0]
        s.text(x + 1.5, top_y + 0.4, f"{int(a.w[n - 1 - j])}" + ("" if a.sampled[n - 1 - j] else "*"),
               size=0.6, halign="middle")
    s.text(isw.pin("VIN")[0] - 10, top_y + 9, f"adc_cdac (behavioral): {n} weights x 2 halves, cu = {a.cu * 1e15:g} fF, "
                   f"C_S = {a.c_s * 1e12:.4f} pF, C_DAC = {a.c_dac * 1e12:.4f} pF",
           style="title_style", halign="start")
    s.text(isw.pin("VIN")[0] - 10, top_y + 7.3, "numbers above the array: the weight of each H/L pair, each half"
           " is w*cu/2; * = not sampled (range extension). H halves: neutral VREFP, dropped by DH; L halves:"
           " neutral VREFN, raised by RL", style="note_style", halign="start")
    L += s.record()
    L.append("ends adc_cdac")
    return "\n".join(L) + "\n"


TARGETS = {
    "rnl": [(REPO_ROOT / "design" / "rnl" / "adc28_blocks.rnl", gen_rnl_blocks),
            (REPO_ROOT / "design" / "rnl" / "adc28_va.rnl", gen_rnl_va)],
    "va-params": [(REPO_ROOT / "design" / "behav" / "veriloga" / "adc_arch.vams", gen_va_params),
                  (REPO_ROOT / "design" / "behav" / "veriloga" / "adc_arch_func.vams", gen_va_funcs),
                  (REPO_ROOT / "design" / "behav" / "adc_cdac.scs", gen_behav_cdac)],
}


def generate(what: str = "all", check: bool = False) -> int:
    from . import gen_docs, gen_tb, gen_top

    targets = dict(TARGETS)
    targets["top"] = [(REPO_ROOT / "design" / "top" / "adc_top.scs", gen_top.gen_top)]
    targets["tb"] = gen_tb.targets()
    targets["docs"] = [(REPO_ROOT / "docs" / "specs.md", gen_docs.gen_specs_md)]
    keys = list(targets) if what == "all" else [what]
    stale = 0
    for k in keys:
        for path, fn in targets[k]:
            text = fn()
            old = path.read_text(encoding="utf-8") if path.exists() else ""
            if check:
                if old != text:
                    stale += 1
                    print(f"STALE {path.relative_to(REPO_ROOT)}")
                    sys.stdout.writelines(difflib.unified_diff(
                        old.splitlines(True), text.splitlines(True), "committed", "generated", n=1))
            elif old != text:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
                print(f"wrote {path.relative_to(REPO_ROOT)}")
    if check and stale:
        print(f"{stale} generated file(s) out of date: run `python -m adcflow gen`")
        return 1
    return 0
